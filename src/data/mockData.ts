function makeAgents(completed: boolean): AgentInfo[] {
  return agentDefinitions.map((a, i) => ({
    ...a,
    status: completed ? 'complete' : i < 7 ? 'complete' : i === 7 ? 'processing' : 'pending',
    result: completed ? getResultText(a.id) : i < 7 ? getResultText(a.id) : undefined,
    duration: completed ? Math.round(200 + Math.random() * 1800) : i < 7 ? Math.round(200 + Math.random() * 1800) : undefined,
  }));
}

